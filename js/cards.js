/* ====================================================================
   REWARD POOLS — built per character from CARD_DEFS
   ==================================================================== */
function rewardPool(rarity, charId){
  const who = charId || (G && G.character) || 'forgeborn';
  return Object.keys(CARD_DEFS).filter(id=>{
    const d = CARD_DEFS[id];
    return d.rarity === rarity && (d.char === 'any' || d.char === who);
  });
}
function rollRewardCards(n, elite){
  const out = [], used = new Set();
  let guard = 0;
  while(out.length < n && guard++ < 200){
    const r = randf();
    let pool;
    if(elite) pool = r < .40 ? 'uncommon' : (r < .72 ? 'rare' : 'common');
    else pool = r < .58 ? 'common' : (r < .92 ? 'uncommon' : 'rare');
    const id = pick(rewardPool(pool));
    if(used.has(id)) continue;
    used.add(id); out.push(id);
  }
  return out;
}
function randomCardOfRarity(rarity){ return pick(rewardPool(rarity)); }
