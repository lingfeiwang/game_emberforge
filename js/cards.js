/* ---- card value helper: vals can be plain or [base, upgraded] ---- */
function cv(card, key){
  const v = CARD_DEFS[card.def].vals[key];
  return Array.isArray(v) ? v[card.upgraded ? 1 : 0] : v;
}
function makeCard(defId, upgraded){ return { id:'c'+(uid++), def:defId, held:0, upgraded:!!upgraded }; }
function cardDef(card){ return CARD_DEFS[card.def]; }
function cardName(card){ return cardDef(card).name + (card.upgraded ? '⁺' : ''); }

const U = (txt) => `<span class="kw">${txt}</span>`;
function hv(card, key){ /* highlight upgraded values green */
  const v = cv(card, key);
  const arr = CARD_DEFS[card.def].vals[key];
  return (card.upgraded && Array.isArray(arr) && arr[0]!==arr[1]) ? `<b class="upval">${v}</b>` : v;
}

